// 配置模块：引脚、量程、采样率、滤波参数、阈值、串口参数。所有可调参数只在这里改。
//
// 【本文件的作用】
// 全工程唯一的"参数总表"。各模块通过 #include "config.h" 读取这些宏，因此调参不需要
// 进任何 .cpp 文件。命名习惯：
//   PIN_*  硬件引脚       *_HZ / *_MS / *_US  时间或频率   单位写在注释里
//   *_N    个数/长度      *_K   无量纲倍数     *_MG  加速度（毫重力，1g=1000mg）
//   *_RATIO 比例          *_TAU_S 时间常数（秒）
// 约束：所有宏在编译期展开，必须是字面常量，不能写成变量或函数调用。
#pragma once
#include <stdint.h>

/* ---------- 引脚（依据 Netlist_PCB1_2026-09-24.tel） ---------- */
#define PIN_SDA        8         // I2C 数据线 SDA，接 MPU6050 的 SDA
#define PIN_SCL        9         // I2C 时钟线 SCL，接 MPU6050 的 SCL
#define PIN_LED_G      10        // 绿：心跳
#define PIN_LED_Y      5         // 黄：振动中 / 故障快闪
#define LED_ACTIVE_LOW 0         // 1 = 灌电流接法（GPIO 低电平点亮）

#define UART_SWAP      0         // 1 = 交换 TX/RX
// 条件编译：UART_SWAP=1 时把 TX/RX 对调。用于 PCB 上画反了、或换了串口模块的情况，
// 只改这一个开关即可，不必动 output.cpp。
#if UART_SWAP
  #define PIN_UART_TX  20        // 串口发送脚（交换后）
  #define PIN_UART_RX  21        // 串口接收脚（交换后）
#else
  #define PIN_UART_TX  21        // 串口发送脚（默认）
  #define PIN_UART_RX  20        // 串口接收脚（默认）
#endif
#define BAUD           115200    // 串口波特率。绘图组 1~3 在 50Hz 下每行约 60 字节，
                                 // 115200 足够；三轴波形组必须用 USB-CDC，见 output.cpp

/* ---------- MPU6050 ---------- */
#define MPU_ADDR         0x68    // AD0 接地
#define I2C_CLOCK        200000UL // I2C 时钟 Hz。400k 更快但线长/上拉不足时易出错，200k 留余量
#define I2C_TIMEOUT_MS   5       // 采样回调里不能长时间阻塞
#define ACCEL_FS_SEL     0       // 0=±2g 1=±4g 2=±8g 3=±16g
                                 // 量程越小分辨率越高：±2g 时 16384 LSB/g（见 mpuLsbPerG）
                                 // 换量程必须同时确认振动峰值不削顶，否则主频会被削平的波形带偏
#define DLPF_CFG         0       // 0 = 加速度带宽 260Hz（保住 180Hz）
                                 // MPU6050 数字低通档位：0=260Hz 1=184Hz 2=94Hz 3=44Hz…
                                 // 选 0 是为了让 220Hz 以内的振动不被片上滤波衰减掉
#define MPU_CLKSEL       0       // 0 = 内部 8MHz；1 = PLL(陀螺X)，频率更稳
                                 // 内部 RC 振荡器随温度漂移会让采样率不准，进而让主频读数偏
#define ACCEL_CLIP_RAW   32700   // |raw| 超过即视为削顶
                                 // int16 满量程 32767，留一点余量。一旦出现说明振动超出所选量程

/* ---------- 采样 ---------- */
#define FS_HZ            1000    // 采样率 Hz。MPU6050 加速度输出率固定 1kHz，故不能超过（下方有断言）
#define RING_N           512     // 环形缓冲深度（2 的幂）
                                 // 512 样本 = 512ms 的缓冲。主循环被串口打印拖慢时的救命余量，
                                 // 太小会丢样（SamplerStats.ringDrop 增长），太大白占内存
#define SMP_JITTER_TOL_US 500    // 相邻样本间隔偏离标称超过此值视为时间不连续
                                 // 标称间隔 = 1000000/FS_HZ = 1000us。esp_timer 回调被
                                 // 高优先级任务挤开时会晚触发，此时样本不再等间隔
#define SMP_BIG_GAP      20      // 缺样超过此数：滤波器与包络整体重置
                                 // 少量缺样只丢主频窗（时间轴已不可信），大量缺样说明采集断档，
                                 // 高通滤波器的历史状态和包络滑窗都已失效，必须整体清零
#define SENSOR_LOST_N    20      // 连续读失败次数 → 判定传感器断线
                                 // 20 次 ≈ 20ms，短暂 I2C 干扰不会误判
#define SENSOR_STALE_MS  100     // 这么久没有成功样本 → 判定断线
                                 // 兜底判据：防止"回调根本没被调用"这种连失败都统计不到的情况
#define RECOVER_PERIOD_MS 1000   // 故障后重连间隔
                                 // 1s 重试一次，既不刷屏也不至于恢复太慢

/* ---------- 信号处理 ---------- */
#define BLOCK_N          128     // 主频估计窗长（2 的幂）
                                 // 128 样本 @1kHz = 128ms 窗。下限要能装下 5 个 60Hz 周期
                                 // (5×16.7=83ms)，上限要短于启停周期的 1/4 以便跟上节奏变化
#define HOP              64      // 窗步长 → 主频更新 15.6Hz
                                 // 相邻窗重叠 50%，既保证刷新率又保证窗内周期完整
#define HP_FC_HZ         70.0f   // 二阶高通截止
                                 // 滤掉重力（0Hz）和手持晃动（<10Hz），保留 60~220Hz 振动。
                                 // 与 FREQ_LO_HZ=60 配合：截止点略低于有效频段下限
#define HP_Q             0.7071f  // 高通品质因数。1/√2 = 巴特沃斯（最平坦通带，无过冲）
#define FREQ_LO_HZ       60.0f   // 有效周期对应频率范围
#define FREQ_HI_HZ       220.0f  // 上限受 BLOCK_N 与 DLPF 带宽双重限制，不要随意抬高
#define MIN_PERIODS      5       // 窗内有效周期数下限
                                 // 少于 5 个周期时周期中位数统计意义不足，宁可判无效
#define ZCL_K            3.6f    // 过零阈值 = K × 带内噪声 sigma
                                 // 3.6σ 是"几乎不会由噪声单独触发"的经验值，比固定阈值更抗
                                 // 器件差异：静置噪声大的板子阈值自动抬高
#define ZCL_MIN_MG       1.0f    // 过零阈值下限 mg。防止标定时噪声极小导致阈值趋近 0 而疯狂误触发
#define ENV_WIN          30      // 包络 RMS 窗（样本）
                                 // 30 样本 @1kHz = 30ms。要长于最低频周期（60Hz→16.7ms）
                                 // 才能让 RMS 平滑，又要短于启停半周期才能分辨启停
#define ENV_HOP          10      // 包络输出间隔 → 100Hz
                                 // 包络不需要每个样本都输出，100Hz 足够驱动状态机并省 CPU
#define CT_LPF_TAU_S     0.2f    // 姿态（低频）支路每轴低通时间常数
                                 // 0.2s 截止 ≈0.8Hz：振动（>60Hz）被彻底压掉，只留下重力方向，
                                 // 因此这一路读的是"模块朝向"而不是"模块在振"

/* ---------- 标定 ---------- */
#define CAL_BIAS_MS      2000    // 阶段A 时长 ms：只采原始数据，求零偏与标准差
#define CAL_NOISE_MS     1200    // 阶段B 时长 ms：跑完整处理链，测带内噪声/静置包络/静置姿态
#define CAL_MAX_STD_MG   20.0f   // 阶段A 原始数据标准差上限：超过说明标定时被碰过
#define CAL_G_TOL_MG     150.0f  // 零偏模长与 1g 的允许偏差
                                 // 静置时零偏矢量模长必然 ≈1000mg（就是重力）。偏差过大说明
                                 // 模块没放平、或标定时在动。两项都合格才置 quality=true

/* ---------- 状态判断 ---------- */
#define TH_HI_K          5.0f    // 启停高阈值 = K × 静置包络
                                 // 5 倍静置噪声：既能抓住弱振动，又不至于把噪声当振动
#define TH_LO_K          2.5f    // 低阈值，必须 < TH_HI_K 才能形成滞回，防止在阈值附近反复翻转
#define TH_HI_MIN_MG     8.0f    // 高阈值下限 mg（标定噪声极小时的兜底）
#define TH_LO_MIN_MG     4.0f    // 低阈值下限 mg
#define SS_CONFIRM       3       // 状态翻转需连续 3 个包络点（30ms）
                                 // 包络输出 100Hz，3 点 = 30ms 去抖，滤掉单点毛刺造成的假翻转
#define SS_EDGE_MAX      16      // 记录的"起"边沿数
                                 // 最多缓存 16 个周期，够算中位数且内存固定（无动态分配）
#define SS_T_MIN_MS      200     // 启停周期下限（5Hz）：更短视为抖动
                                 // 比 200ms 更快的"启停"不像是人工操作，多半是包络在阈值附近抖动
#define SS_T_MAX_MS      10000   // 启停周期上限（0.1Hz）：更长视为新一轮
                                 // 超过 10s 没再启动，认为上一次操作已经结束，重新开始计数
#define SS_MIN_PERIODS   2       // 至少 2 个完整周期才给启停频率
                                 // 只有 1 个周期只能算出瞬时值，谈不上"频率"
#define SS_USE_PERIODS   4       // 取最近 N 个周期的中位数
                                 // 取中位数而不是平均：抗偶尔一次手抖造成的异常周期
#define SS_TIMEOUT_K     2.0f    // 超过 K × 当前周期没有新边沿 → 启停频率失效
                                 // 自适应超时：启停快时快速失效，启停慢时给足等待时间
#define SS_CONSIST_RATIO 1.5f    // 参与统计的周期 最大/最小 超过此比值 → 节奏不稳，不给读数
                                 // 比值大说明用户节奏忽快忽慢，此时报一个"平均频率"是误导
#define FREQ_STALE_MS    300     // 主频结果超过此时间未更新 → 失效
                                 // 窗步长 64 样本 = 64ms 出一次结果，300ms ≈ 4~5 个窗都没出，
                                 // 说明确实没有持续振动了（例如振动已停止但状态机还没翻转）

#define CT_MODE          1       // 0 = 仅姿态变化；1 = 姿态变化 或 振动中
                                 // 模式 1 更符合"接触"的物理含义：手按上去既改变姿态、
                                 // 也往往带轻微振动；模式 0 只认姿态，适合传感器贴在柔性件上的场景
#define CT_K             4.0f    // 接触阈值 = K × 静置姿态偏差
#define CT_MIN_MG        30.0f   // 接触阈值下限 mg。低于此值会把手持微晃当成接触
#define CT_OFF_RATIO     0.6f    // 释放阈值 = 比例 × 接触阈值（滞回）
                                 // 0.6 使"按下"和"松开"用不同阈值，避免在临界点反复报接触
#define CT_CONFIRM_MS    100     // 接触状态翻转确认时间 ms。100ms 比启停的 30ms 长，
                                 // 因为姿态支路本身响应慢（时间常数 0.2s），确认太久又会觉得迟钝

/* ---------- 输出 ---------- */
#define PLOT_MS          20      // 绘图行 50Hz
                                 // 串口绘图器刷新率。再高会挤占主循环时间，导致环形缓冲溢出
#define DBG_MS           200     // 调试文字行 5Hz
#define PLOT_DEFAULT     1       // 上电默认绘图组（见 output.h），0 = 不绘图

// 编译期自检 1：环形缓冲用位与取模（& (N-1)）替代取余，前提是 N 必须是 2 的幂。
// 若误改成非 2 的幂，取模会出错且不报错，所以这里直接编译失败拦下来。
#if (BLOCK_N & (BLOCK_N - 1)) || (RING_N & (RING_N - 1))
  #error "BLOCK_N 与 RING_N 必须是 2 的幂"
#endif
// 编译期自检 2：MPU6050 加速度输出率固定 1kHz，采样率定高了只会读到重复样本。
#if (FS_HZ > 1000)
  #error "MPU6050 加速度输出率固定 1kHz，FS_HZ 不能超过 1000"
#endif
